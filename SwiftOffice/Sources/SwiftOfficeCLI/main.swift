import Foundation
import ArgumentParser
import SwiftSlides

actor PresentationRegistry: Sendable {
    static let shared = PresentationRegistry()
    
    private var registry: [String: @Sendable () -> any Presentation] = [:]
    
    private init() {}
    
    func register(_ factory: @escaping @Sendable () -> any Presentation, name: String) {
        registry[name] = factory
    }
    
    func unregister(_ name: String) {
        registry.removeValue(forKey: name)
    }
    
    subscript(_ name: String) -> (@Sendable () -> any Presentation)? {
        registry[name]
    }
    
    func getAllPresentations() -> [String] {
        Array(registry.keys)
    }
}

