@main
struct SwiftOfficeCLI: AsyncParsableCommand {
    static let configuration = CommandConfiguration(
        commandName: "swiftoffice",
        abstract: "Swift Office CLI Tool - Generate office documents from Swift structs"
    )
    
    @Argument(help: "The presentation struct name")
    var structName: String
    
    @Option(name: .shortAndLong, help: "Output file path (default: <structName>.pptx)")
    var output: String?
    
    @Flag(name: .shortAndLong, help: "Verbose output")
    var verbose: Bool = false
    
    func run() async throws {
        await PresentationRegistry.shared.register({ DemoPresentation() }, name: "DemoPresentation")
        await PresentationRegistry.shared.register({ SimpleDemo() }, name: "SimpleDemo")
        
        print("Looking for presentation: \(structName)")
        
        guard let factory = await PresentationRegistry.shared[structName] else {
            print("Error: Unknown presentation '\(structName)'")
            print("\nAvailable presentations:")
            for name in await PresentationRegistry.shared.getAllPresentations().sorted() {
                print("  • \(name)")
            }
            throw ExitCode.failure
        }
        
        let presentation = factory()
        let outputPath = output ?? "\(structName).pptx"
        
        if verbose {
            print("Generating: \(presentation.title)")
            print("Sections: \(presentation.sections.count)")
            print("Total slides: \(presentation.sections.reduce(0) { $0 + $1.slides.count })")
        }
        
        if #available(macOS 10.15, *) {
            try await presentation.toPPTX(outputPath: outputPath)
            print("✓ Generated: \(outputPath)")
        } else {
            print("Error: PPTX generation requires macOS 10.15 or later")
            throw ExitCode.failure
        }
    }
}
